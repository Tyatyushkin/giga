from __future__ import annotations

from dataclasses import dataclass
from typing import ClassVar


# ==========================================================================
# TC-J01-00 — Main path: full registration + first play
# ==========================================================================

@dataclass(frozen=True)
class TC_J01_00_Data:
    """Тестовые данные: основной сценарий (REQ-01 – REQ-06)."""

    PHONE: ClassVar[str] = "+7 999 000-00-11"
    """Номер телефона, не зарегистрированный ранее."""

    CONFIRMATION_CODE: ClassVar[str] = "1111"
    """Валидный код из 4 цифр (SMS)."""

    GENRES: ClassVar[tuple[str, ...]] = ("Электроника", "Хип-хоп", "Инди")
    """Ровно 3 жанра — нижняя граница REQ-02."""

    SEARCH_QUERY: ClassVar[str] = "Дельфин"
    """Запрос, который возвращает результаты во всех вкладках."""

    FIRST_TRACK_TITLE: ClassVar[str] = "Весна"
    """Название первого трека (исполнитель: Дельфин)."""

    FIRST_TRACK_ARTIST: ClassVar[str] = "Дельфин"
    """Имя исполнителя первого трека."""

    SECOND_TRACK_TITLE: ClassVar[str] = "Любовь"
    """Название второго трека для очереди."""

    SECOND_TRACK_ARTIST: ClassVar[str] = "Дельфин"
    """Имя исполнителя второго трека."""


